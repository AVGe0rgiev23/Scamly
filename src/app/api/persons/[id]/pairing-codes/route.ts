// POST /api/persons/:id/pairing-codes: a new 6-digit code to pair the phone of this
// protected person (family, OWNER only; BUILD_PLAN 3, #14 and section 5).
// 201 { code: "482915", expiresAt }. Old unused codes of this person are cancelled.
// Not the owner, or no such person -> 404 (we don't reveal that it exists).

import { IdParamSchema } from "@/schemas/persons";
import { requireRole } from "@/server/auth/requireRole";
import { handleApiError, json, notFound } from "@/server/http/errors";
import { assertSameOrigin } from "@/server/security/origin";
import { createPairingCode, createPairingDeps } from "@/server/services/pairingService";
import { createAdminClient } from "@/server/supabase/adminClient";
import { createUserClient } from "@/server/supabase/userClient";

// RouteContext<"..."> is generated by Next.js: it tells TypeScript that this route
// has an `id` in its URL.
export async function POST(
  request: Request,
  context: RouteContext<"/api/persons/[id]/pairing-codes">,
) {
  try {
    assertSameOrigin(request); // 0. from our own site? (CSRF)
    const client = await createUserClient();
    const actor = await requireRole(["family"], client); // 1. who are you? (401/403)
    const { id } = await context.params;
    const personId = IdParamSchema.safeParse(id); // 2. valid id? (else 404, like an unknown id)
    if (!personId.success) {
      throw notFound();
    }
    const deps = createPairingDeps(client, createAdminClient());
    const result = await createPairingCode(deps, actor, personId.data); // 3. owner check + code
    return json(result, 201); // 4. respond
  } catch (error) {
    return handleApiError(error);
  }
}
